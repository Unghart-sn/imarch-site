-- 2026-11-16: Product Catalog (Step A)
-- Adds: products, product_prices (append-only, timelock via active_from),
--       get_current_price(), orders.product_code
-- Applied via Supabase Dashboard SQL Editor on 2026-11-16.

begin;

create table if not exists public.products (
  product_code    text primary key,
  product_name    text not null,
  description     text,
  billing_period  text not null check (billing_period in ('one_time','monthly','annual')),
  active          boolean not null default true,
  created_at      timestamptz not null default now()
);

create table if not exists public.product_prices (
  id            bigint generated by default as identity primary key,
  product_code  text not null references public.products(product_code),
  price_micro   int not null check (price_micro > 0),
  active_from   timestamptz not null default now(),
  published_at  timestamptz not null default now(),
  notes         text,
  created_at    timestamptz not null default now()
);

create index if not exists product_prices_code_active_idx
  on public.product_prices (product_code, active_from desc);

create or replace function public.prevent_product_prices_mutation()
returns trigger language plpgsql as $$
begin
  raise exception 'product_prices is append-only: % not allowed', tg_op;
end;
$$;

drop trigger if exists product_prices_no_update on public.product_prices;
create trigger product_prices_no_update
  before update or delete on public.product_prices
  for each row execute function public.prevent_product_prices_mutation();

insert into public.products (product_code, product_name, description, billing_period) values
  ('certificate', 'Digital Certificate', 'Cryptographic certificate issuance (single file)', 'one_time'),
  ('safe_100mb',  'Digital Safe 100 MB',  'Encrypted file vault rental (100 MB per month)', 'monthly')
on conflict (product_code) do nothing;

insert into public.product_prices (product_code, price_micro, active_from, notes)
select 'certificate', 20, now() - interval '1 second', 'initial price'
where not exists (
  select 1 from public.product_prices where product_code = 'certificate'
);

insert into public.product_prices (product_code, price_micro, active_from, notes)
select 'safe_100mb', 10, now() - interval '1 second', 'initial price'
where not exists (
  select 1 from public.product_prices where product_code = 'safe_100mb'
);

create or replace function public.get_current_price(p_product_code text)
returns table (product_code text, price_micro int, billing_period text)
language sql stable security definer set search_path = public as $$
  select pp.product_code, pp.price_micro, p.billing_period
  from public.product_prices pp
  join public.products p on p.product_code = pp.product_code
  where pp.product_code = p_product_code
    and pp.active_from <= now()
    and p.active = true
  order by pp.active_from desc
  limit 1;
$$;

grant execute on function public.get_current_price(text) to anon, authenticated, service_role;

alter table public.orders
  add column if not exists product_code text not null default 'certificate'
    references public.products(product_code);

create index if not exists orders_product_code_idx on public.orders (product_code);

alter table public.products enable row level security;
alter table public.product_prices enable row level security;

drop policy if exists "products readable by all" on public.products;
create policy "products readable by all" on public.products
  for select using (true);

drop policy if exists "product_prices readable by all" on public.product_prices;
create policy "product_prices readable by all" on public.product_prices
  for select using (true);

grant select on public.products to anon, authenticated;
grant select on public.product_prices to anon, authenticated;

commit;
